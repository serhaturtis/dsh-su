/**
 * Bundle the engine and the client body into one file the shell can load.
 *
 * Why this exists: a client-module bundle cannot `require` relative files — only
 * platform seeds like `react` resolve — so the engine has to be flattened into
 * the bundle. Rather than teach the engine about bundlers, this script does the
 * one transformation our own code needs: `import { a } from './x.js'` becomes a
 * registry lookup, and `export` is stripped and re-attached.
 *
 * It refuses to guess. An import form it does not recognise is an error, so a
 * future module cannot silently produce a broken bundle.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const rigDir = join(root, 'src', 'rig')

/** Engine modules, in dependency order (order only matters for readability). */
const MODULES = ['math.js', 'format.js', 'compile.js', 'clip.js', 'pose.js', 'ik.js', 'spring.js', 'lint.js', 'render.js', 'editor.js', 'demo.js'].filter(
	(name) => {
		try {
			readFileSync(join(rigDir, name))
			return true
		} catch {
			return false
		}
	},
)

const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)'$/gm
const EXPORT_LIST = /^export\s*\{([^}]*)\}$/gm

/**
 * Transform one module body: imports become registry lookups, exports become
 * assignments collected at the end of the module.
 */
export function transformModule(source, name) {
	if (/^\s*import\s+\w/m.test(source.replace(IMPORT, ''))) {
		throw new Error(`${name}: unsupported import form (only named imports are bundled)`)
	}
	const exported = []
	let body = source.replace(IMPORT, (_match, names, specifier) => `const {${names}} = __require('${specifier}')`)
	body = body.replace(EXPORT_LIST, (_match, names) => {
		for (const entry of names.split(',')) {
			const name2 = entry.trim()
			if (name2.length > 0) exported.push(name2)
		}
		return ''
	})
	body = body.replace(/^export\s+function\s+(\w+)/gm, (_match, name2) => {
		exported.push(name2)
		return `function ${name2}`
	})
	body = body.replace(/^export\s+class\s+(\w+)/gm, (_match, name2) => {
		exported.push(name2)
		return `class ${name2}`
	})
	body = body.replace(/^export\s+const\s+(\w+)/gm, (_match, name2) => {
		exported.push(name2)
		return `const ${name2}`
	})
	if (/^\s*export\s/m.test(body)) throw new Error(`${name}: unsupported export form`)
	const trailer = exported.map((name2) => `\texports.${name2} = ${name2}`).join('\n')
	return `${body}\n${trailer}\n`
}

function build() {
	const registry = MODULES.map((module) => {
		const source = readFileSync(join(rigDir, module), 'utf8')
		return `__define('./${module}', function (__require, exports) {\n${transformModule(source, module)}})`
	}).join('\n\n')

	const body = readFileSync(join(root, 'src', 'client.body.js'), 'utf8')
	const names = MODULES.map((module) => module.replace(/\.js$/, ''))
	const engineExposure = names
		.map((name) => `\t${JSON.stringify(name)}: __require('./${name}.js')`)
		.join(',\n')

	const out = `/* Generated by scripts/build-client.mjs — do not edit. */
;(function () {
'use strict'
if (typeof window === 'undefined' || window.__ModuleLoader__ === undefined) return

var __modules = Object.create(null)
function __define(name, factory) {
	__modules[name] = { factory: factory, exports: null }
}
function __require(name) {
	var module = __modules[name]
	if (module === undefined) throw new Error('rig-studio bundle: unknown module ' + name)
	if (module.exports === null) {
		module.exports = {}
		module.factory(__require, module.exports)
	}
	return module.exports
}

${registry}

var RIG_STUDIO = {
${engineExposure}
}

${body}
})()
`

	mkdirSync(join(root, 'dist'), { recursive: true })
	writeFileSync(join(root, 'dist', 'client.js'), out)
	return out
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const out = build()
	console.log(`wrote dist/client.js (${out.length} bytes, ${MODULES.length} modules)`)
}

export { build, MODULES }
